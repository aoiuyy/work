import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const UI_STYLES = [
  'ui/styles/01-base-and-audio.css',
  'ui/styles/02-stream-and-drawer.css',
  'ui/styles/03-compact-shell.css',
  'ui/styles/04-features-and-motion.css',
];

export const UI_SCRIPTS = [
  'ui/shared/icons.js',
  'ui/shared/rpc.js',
  'ui/shared/markdown.js',
  'ui/features/music/ItunesPlayer.js',
  'ui/features/chat/ChatChannels.js',
  'ui/features/chat/NotesBrainstormView.js',
  'ui/features/repo/RepoCard.js',
  'ui/features/repo/RepoMeshView.js',
  'ui/features/intel/IntelReaderView.js',
  'ui/features/settings/SettingsPanel.js',
  'ui/features/shell/window-geometry.js',
  'ui/features/shell/BubbleHUD.js',
  'ui/features/shell/WorkMainPanel.js',
];

export async function assembleClientBundle(root) {
  const template = await readFile(path.join(root, 'ui/client.template.js'), 'utf8');
  if (template.split('/* WORK_STYLES */').length !== 2) throw new Error('Expected exactly one style marker');
  if (template.split('/* WORK_COMPONENTS */').length !== 2) throw new Error('Expected exactly one component marker');
  const [styles, scripts] = await Promise.all([
    Promise.all(UI_STYLES.map(async file => (await readFile(path.join(root, file), 'utf8')).replace(/^\uFEFF/, ''))),
    Promise.all(UI_SCRIPTS.map(async file => (await readFile(path.join(root, file), 'utf8')).replace(/^\uFEFF/, ''))),
  ]);
  return (
    '// Generated by node scripts/build-ui.mjs. Edit ui/ styles, shared, features, or client.template.js.\n' +
    template
      .replace('/* WORK_STYLES */', styles.join('\n'))
      .replace('/* WORK_COMPONENTS */', scripts.join('\n'))
  );
}

if (path.resolve(process.argv[1] || '') === path.resolve(fileURLToPath(import.meta.url))) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const output = await assembleClientBundle(root);
  await writeFile(path.join(root, 'client.js'), output);
  console.log(`Built client.js from ${UI_STYLES.length} stylesheets and ${UI_SCRIPTS.length} UI modules.`);
}
